function t(key){ return I18N.en[key] ?? key; }
function applyLanguage(){
  document.documentElement.lang='en';
  document.querySelectorAll('[data-i18n]').forEach(el=>{const v=I18N.en[el.dataset.i18n];if(v!==undefined)el.textContent=v;});
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el=>{const v=I18N.en[el.dataset.i18nPlaceholder];if(v!==undefined)el.placeholder=v;});
  document.querySelectorAll('[data-i18n-content-placeholder]').forEach(el=>{const v=I18N.en[el.dataset.i18nContentPlaceholder];if(v!==undefined)el.dataset.placeholder=v;});
}
function setLanguage(){ applyLanguage(); }
